package org.java_code.condition;

public class switch01 {

	public static void main(String[] args) {
		// 선택한 번호에 따라 정답 또는 오답 출력 (정답은 2)
		int a = 2;
		
		switch (a) {
			case 1:
				System.out.println("오답");
				break;
			case 2:
				System.out.println("정답");
				break;
			case 3:
				System.out.println("오답");
				break;
			case 4:
				System.out.println("오답");
				break;
			case 5:
				System.out.println("오답");
				break;
		}

	}

}
